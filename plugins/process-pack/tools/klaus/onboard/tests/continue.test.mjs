const prices = async () => ({ ok: true, json: async () => ({ data: [{ id: 'z-ai/glm-5.3-flash', pricing: { prompt: '0.0000000392', completion: '0.0000002' } }] }) })

let sample
let saved
let logs
let checks
const checker = async (_url, init) => {
  checks += 1
  const prompt = JSON.parse(init.body).messages[0].content
  const verdict = prompt.includes('Component: LinkButton') ? { verdict: 'fail', reason: 'it is also used for buttons that submit' } : { verdict: 'pass', reason: 'matches the places it is used' }
  return { ok: true, status: 200, json: async () => ({ choices: [{ message: { content: JSON.stringify(verdict) } }], usage: { prompt_tokens: 300, completion_tokens: 55, cost: 0.00003 } }) }
}

beforeEach(() => {
  sample = makeGitSample()
  logs = { codex: path.join(sample.base, 'codex.log'), gh: path.join(sample.base, 'gh.log') }
  saved = { ...process.env }
  checks = 0
  process.env.PATH = `${STUBS}${path.delimiter}${process.env.PATH}`
  process.env.STUB_LOG = logs.codex
  process.env.STUB_GH_LOG = logs.gh
  process.env.OPENROUTER_API_KEY = 'sk-test-not-real'
})
afterEach(() => {
  for (const key of Object.keys(process.env)) if (!(key in saved)) delete process.env[key]
  Object.assign(process.env, saved)
  sample.cleanup()
})

async function estimate() {
  const { onboarding, folders } = readOnboardingConfig(sample.repo)
  const result = await buildEstimate({ plan: buildPlan({ root: sample.repo, folders, onboarding }), onboarding, fetchImpl: prices })
  fs.mkdirSync(workFolder(sample.repo), { recursive: true })
  writeJsonFile(path.join(workFolder(sample.repo), 'estimate.json'), result)
  return result
}

const run = (estimated, extra = {}) => runOnboarding({ repo: sample.repo, approve: estimated.id, codex: path.join(STUBS, 'codex'), fetchImpl: checker, log: () => {}, commitTrailers: ['Co-Authored-By: Test <t@example.com>'], bodyFooter: 'Generated by the test.', ...extra })
const lines = (file) => (fs.existsSync(file) ? fs.readFileSync(file, 'utf8').trim().split('\n').filter(Boolean) : [])
const codexCalls = () => lines(logs.codex).length
const ghCalls = () => lines(logs.gh).map((l) => JSON.parse(l))
const tip = (ref) => sample.git('rev-parse', ref).trim()
const onOrigin = (branch) => sample.git('ls-remote', '--heads', 'origin', `refs/heads/${branch}`).trim().split(/\s+/)[0] ?? ''

/** A gh that makes the first `allowed` pull requests and fails on the next, as a stop part way does. */
function ghThatStopsAfter(allowed) {
  const dir = path.join(sample.base, 'bin')
  fs.mkdirSync(dir, { recursive: true })
  fs.writeFileSync(path.join(dir, 'gh'), `#!/usr/bin/env node
const fs = require('fs')
const a = process.argv.slice(2)
if (a[0] === 'pr' && a[1] === 'create') {
  const made = fs.existsSync(${JSON.stringify(logs.gh)}) ? fs.readFileSync(${JSON.stringify(logs.gh)}, 'utf8').split('\\n').filter((l) => l.includes('"create"')).length : 0
  if (made >= ${allowed}) { console.error('boom'); process.exit(1) }
}
process.argv = [process.argv[0], ${JSON.stringify(path.join(STUBS, 'gh'))}, ...a]
import(${JSON.stringify(path.join(STUBS, 'gh'))})
`)
  fs.chmodSync(path.join(dir, 'gh'), 0o755)
  const before = process.env.PATH
  process.env.PATH = `${dir}${path.delimiter}${before}`
  return () => { process.env.PATH = before }
}

/**
 * Merges a branch into main as the landing service does, then formats the files the way a commit
 * hook with a formatter would: JSON indented another way, Markdown with other whitespace. Then
 * main moves on with a commit that has nothing to do with the run.
 */
function mergeWithFormatting(branch, numbers) {
  sample.git('merge', '-q', '--no-ff', branch, '-m', `Merge pull request from ${branch}`)
  const json = path.join(sample.repo, 'inventory.json')
  fs.writeFileSync(json, `${JSON.stringify(JSON.parse(fs.readFileSync(json, 'utf8')), null, 4)}\n`)
  for (const rel of ['INVENTORY.md', 'docs/klaus/duplicates.md', 'docs/klaus/decisions.md']) {
    const file = path.join(sample.repo, rel)
    fs.writeFileSync(file, fs.readFileSync(file, 'utf8').split('\n').map((l) => (l ? `${l}  ` : l)).join('\n').replace(/\n\n/g, '\n\n\n'))
  }
  sample.git('commit', '-qam', 'Format')
  fs.writeFileSync(path.join(sample.repo, 'NOTES.md'), 'Something else landed.\n')
  sample.git('add', 'NOTES.md')
  sample.git('commit', '-qm', 'Something else')
  sample.git('push', '-q', 'origin', 'main')
  process.env.STUB_GH_MERGED = numbers.join(',')
}

test('a run whose first pull request merged continues at the second: no model call, the open one replaced, the local third branch made again', async () => {
  const estimated = await estimate()
  // The first run stops after two pull requests, as Meridian's did.
  const restore = ghThatStopsAfter(2)
  await assert.rejects(() => run(estimated), /gh pr create .* failed/)
  restore()
  assert.deepEqual([codexCalls(), checks], [3, 4])
  // The third branch is only here, with a commit someone added to it.
  sample.git('push', '-q', 'origin', '--delete', BRANCHES[2])
  sample.git('checkout', '-q', BRANCHES[2])
  fs.writeFileSync(path.join(sample.repo, 'extra.txt'), 'mine\n')
  sample.git('add', 'extra.txt')
  sample.git('commit', '-qm', 'a commit of mine')
  sample.git('checkout', '-q', 'main')
  mergeWithFormatting(BRANCHES[0], [1])
  const listOnOrigin = onOrigin(BRANCHES[0])
  const oldPurposes = onOrigin(BRANCHES[1])

  const messages = []
  const { report } = await run(estimated, { log: (m) => messages.push(m) })
  assert.deepEqual([codexCalls(), checks], [3, 4], 'the second run made no model call')
  assert.equal(report.continuedAt, 2)
  assert.deepEqual(report.alreadyMerged, [{ step: 1, number: 1, url: 'https://github.com/acme/sample/pull/1' }])
  assert.deepEqual(report.replaced, [{ step: 2, number: 2, url: 'https://github.com/acme/sample/pull/2' }])
  assert.ok(messages.some((m) => /The first pull request's files are on main, as this plan writes them \(formatting aside\), so the run continues at the second\./.test(m)), messages.join('\n'))

  const calls = ghCalls()
  assert.deepEqual(calls.filter((c) => c.action === 'close').map((c) => c.number), [2])
  const created = calls.filter((c) => c.action === 'create')
  assert.deepEqual(created.map((c) => [c.number, c.base, c.head]), [[1, 'main', BRANCHES[0]], [2, BRANCHES[0], BRANCHES[1]], [3, 'main', BRANCHES[1]], [4, BRANCHES[1], BRANCHES[2]]])
  const body = calls.filter((c) => c.action === 'edit' && c.number === 3).at(-1).body
  assert.match(body, /It replaces #2, which an earlier run of this plan opened/)
  assert.match(body, /1\. #1: the list of components at 1\.0\.0, and the duplicates\. Merged\./)

  // The first branch is as it was; the second is cut again from main and pushed over the old one; the third is made again from the second.
  assert.equal(onOrigin(BRANCHES[0]), listOnOrigin)
  assert.notEqual(onOrigin(BRANCHES[1]), oldPurposes)
  assert.equal(onOrigin(BRANCHES[1]), tip(BRANCHES[1]))
  assert.equal(tip(`${BRANCHES[1]}^`), tip('main'))
  assert.equal(tip(`${BRANCHES[2]}^`), tip(BRANCHES[1]))
  assert.equal(onOrigin(BRANCHES[2]), tip(BRANCHES[2]))
  assert.equal(sample.git('ls-tree', '--name-only', BRANCHES[2], 'extra.txt').trim(), '')
  assert.ok(messages.some((m) => /The branch klaus\/onboarding-3-stories is made again from the plan\. It was at [0-9a-f]{10}/.test(m)))
  // The second pull request holds the purposes and the rebuilt list, on top of the merged one.
  const changed = sample.git('diff', '--name-only', 'main', BRANCHES[1]).trim().split('\n').sort()
  assert.deepEqual(changed, ['INVENTORY.md', 'apps/web/src/app/dashboard/_components/ActivityFeed.tsx', 'apps/web/src/marketing/Hero.tsx', 'docs/klaus/purposes.md', 'inventory.json', 'packages/ui/src/PrimaryButton.tsx'])
  assert.ok(report.comparison.every((r) => r.within !== false), JSON.stringify(report.comparison.filter((r) => r.within === false)))
  assert.equal(sample.git('rev-parse', '--abbrev-ref', 'HEAD').trim(), 'main')
  assert.equal(sample.git('status', '--porcelain', '--untracked-files=all').trim(), '')
})

test('the estimate says where a run would continue and which model results it would use again', async () => {
  const estimated = await estimate()
  const restore = ghThatStopsAfter(2)
  await assert.rejects(() => run(estimated), /failed/)
  restore()
  mergeWithFormatting(BRANCHES[0], [1])
  const printed = []
  const original = console.log
  console.log = (...a) => printed.push(a.join(' '))
  try {
    assert.equal(await main(['estimate', '--repo', sample.repo], { fetchImpl: prices }), 0)
  } finally {
    console.log = original
  }
  const text = printed.join('\n')
  assert.ok(text.includes(`plan ${estimated.id}`), 'the plan is the same')
  assert.match(text, /the run continues at the second/)
  assert.match(text, /Model results saved for this plan: 3 writer calls of 3 and 4 checks\. The run uses them again instead of calling the model, so it makes 0 writer calls, and at most 0 checks\./)
})

test('merged files that are not what the plan writes stop the run, with the files and the place they differ', async () => {
  const estimated = await estimate()
  await run(estimated)
  sample.git('merge', '-q', '--no-ff', BRANCHES[0], '-m', 'Merge pull request #1')
  const json = path.join(sample.repo, 'inventory.json')
  const list = JSON.parse(fs.readFileSync(json, 'utf8'))
  const button = list.entries.findIndex((e) => e.name === 'Button')
  list.entries[button].version = '1.0.1'
  fs.writeFileSync(json, `${JSON.stringify(list, null, 2)}\n`)
  const md = path.join(sample.repo, 'docs/klaus/duplicates.md')
  fs.writeFileSync(md, fs.readFileSync(md, 'utf8').replace(/PrimaryButton/, 'MainButton'))
  sample.git('commit', '-qam', 'edited after the merge')
  sample.git('push', '-q', 'origin', 'main')
  process.env.STUB_GH_MERGED = '1'
  const before = { calls: ghCalls().length, codex: codexCalls(), checks }

  await assert.rejects(() => run(estimated), (e) => {
    assert.ok(e instanceof UserError)
    assert.match(e.message, /The first pull request's files are on main, but not as this plan writes them, so the run cannot continue from them and does not overwrite them\./)
    assert.match(e.message, new RegExp(`- inventory\\.json: at entries\\[${button}\\]\\.version \\(Button in packages/ui/src/Button\\.tsx\\) the plan writes "1\\.0\\.0", and it holds "1\\.0\\.1"`))
    assert.match(e.message, /- docs\/klaus\/duplicates\.md: the plan writes .*PrimaryButton.*, and it holds .*MainButton/)
    return true
  })
  assert.deepEqual([codexCalls(), checks], [before.codex, before.checks], 'no model call')
  assert.deepEqual(ghCalls().slice(before.calls).filter((c) => c.action !== 'list'), [], 'no pull request closed or made')
  assert.equal(sample.git('status', '--porcelain', '--untracked-files=all').trim(), '')
})

test('a run whose purposes merged makes only the stories again, with no model call and no checker key', async () => {
  await run(await estimate())
  assert.deepEqual([codexCalls(), checks], [3, 4])
  sample.git('merge', '-q', '--no-ff', BRANCHES[1], '-m', 'Merge pull requests #1 and #2')
  sample.git('push', '-q', 'origin', 'main')
  process.env.STUB_GH_MERGED = '1,2'
  delete process.env.OPENROUTER_API_KEY
  // The components now hold their purposes, so the plan is a new one.
  const again = await estimate()

  const { report } = await run(again, { env: process.env })
  assert.deepEqual([codexCalls(), checks], [3, 4], 'no model call')
  assert.equal(report.continuedAt, 3)
  const calls = ghCalls()
  assert.deepEqual(calls.filter((c) => c.action === 'close').map((c) => c.number), [3])
  assert.deepEqual(calls.filter((c) => c.action === 'create').at(-1), { ...calls.filter((c) => c.action === 'create').at(-1), base: 'main', head: BRANCHES[2], number: 4 })
  assert.equal(report.comparison.find((r) => r.metric === 'Writer calls').within, null)
  assert.equal(tip(`${BRANCHES[2]}^`), tip('main'))
  assert.deepEqual(sample.git('diff', '--name-only', 'main', BRANCHES[2]).trim().split('\n').sort(), ['apps/web/src/marketing/Hero.stories.tsx', 'docs/klaus/stories.json', 'docs/klaus/stories.md', 'packages/ui/src/LinkButton.stories.tsx', 'packages/ui/src/PrimaryButton.stories.tsx'])
})

test('a run with all three merged has nothing to do, and one with the stories merged before the purposes is refused', async () => {
  await run(await estimate())
  sample.git('merge', '-q', '--no-ff', BRANCHES[2], '-m', 'Merge all three')
  sample.git('push', '-q', 'origin', 'main')
  const result = await run(await estimate())
  assert.equal(result.done, true)

  sample.git('rm', '-q', 'docs/klaus/purposes.md')
  sample.git('commit', '-qm', 'drop the purposes record')
  sample.git('push', '-q', 'origin', 'main')
  const last = await estimate()
  await assert.rejects(() => run(last), /stories were merged before the purposes/)
})

test('the list compares as the same when it was made at an earlier commit of this branch, and not at any other commit', async () => {
  const { contentDifference } = await import('../stages.mjs')
  const first = tip('HEAD')
  fs.writeFileSync(path.join(sample.repo, 'NOTES.md'), 'later\n')
  sample.git('add', 'NOTES.md')
  sample.git('commit', '-qm', 'later')
  const list = (commit, extra = {}) => `${JSON.stringify({ schemaVersion: 1, entries: [], versioned: { release: 'baseline', commit }, ...extra }, null, 2)}\n`
  const expected = list(tip('HEAD'))
  assert.equal(contentDifference({ repo: sample.repo, rel: 'inventory.json', expected, actual: `${JSON.stringify(JSON.parse(list(first)))}\n` }), null)
  assert.match(contentDifference({ repo: sample.repo, rel: 'inventory.json', expected, actual: list('0123456789abcdef0123456789abcdef01234567') }), /^at versioned\.commit the plan writes/)
  assert.match(contentDifference({ repo: sample.repo, rel: 'inventory.json', expected, actual: list(first, { entries: [{ name: 'X' }] }) }), /^at entries \(a list of 0, and it has 1\)/)
  assert.equal(contentDifference({ repo: sample.repo, rel: 'docs/a.md', expected: '# A\n\n| a | b |\n', actual: '# A  \n\n\n| a | b |' }), null)
})
