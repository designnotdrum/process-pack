const prices = async () => ({ ok: true, json: async () => ({ data: [{ id: 'z-ai/glm-5.3-flash', pricing: { prompt: '0.0000000392', completion: '0.0000002' } }] }) })
const checker = async () => ({ ok: true, status: 200, json: async () => ({ choices: [{ message: { content: JSON.stringify({ verdict: 'pass', reason: 'matches the places it is used' }) } }], usage: { prompt_tokens: 300, completion_tokens: 55, cost: 0.00003 } }) })

/**
 * A pre-commit hook that rewrites code, as `oxlint --fix` run by lint-staged does. HOOK_MODE picks
 * what it does. `rewrite` changes one line of PrimaryButton.tsx, outside any comment, and stages the
 * file again. `remove` deletes that line. `long` appends a 250 character comment to it. `many` adds a code span to the end of every line of every component file. `none` changes nothing. A hook run is logged, so a test can tell the hook was not skipped.
 */
const LONG = 'y'.repeat(250)
const HOOK = `#!/bin/sh
echo hook >> "$HOOK_RUNS_LOG"
case "$HOOK_MODE" in
  many)
    for file in $(git diff --cached --name-only | grep -E '\\.tsx$' | grep -v '\\.stories\\.tsx$'); do
      sed 's|$| // \`x\`|' "$file" > "$file.tmp" && mv "$file.tmp" "$file"
      git add "$file"
    done ;;
  remove)
    file=packages/ui/src/PrimaryButton.tsx
    if git diff --cached --name-only | grep -q -x "$file"; then
      sed '/^      disabled={disabled}$/d' "$file" > "$file.tmp" && mv "$file.tmp" "$file"
      git add "$file"
    fi ;;
  long)
    file=packages/ui/src/PrimaryButton.tsx
    if git diff --cached --name-only | grep -q -x "$file"; then
      sed 's|^      disabled={disabled}$|      disabled={disabled} // ${LONG}|' "$file" > "$file.tmp" && mv "$file.tmp" "$file"
      git add "$file"
    fi ;;
  rewrite)
    file=packages/ui/src/PrimaryButton.tsx
    if git diff --cached --name-only | grep -q -x "$file"; then
      sed 's|^      disabled={disabled}$|      disabled={Boolean(disabled)}|' "$file" > "$file.tmp" && mv "$file.tmp" "$file"
      git add "$file"
    fi ;;
esac
exit 0
`

let sample
let saved
let logs
beforeEach(() => {
  sample = makeGitSample()
  logs = { codex: path.join(sample.base, 'codex.log'), gh: path.join(sample.base, 'gh.log'), hookRuns: path.join(sample.base, 'hook-runs.log') }
  saved = { ...process.env }
  process.env.PATH = `${STUBS}${path.delimiter}${process.env.PATH}`
  process.env.STUB_LOG = logs.codex
  process.env.STUB_GH_LOG = logs.gh
  process.env.HOOK_RUNS_LOG = logs.hookRuns
  process.env.OPENROUTER_API_KEY = 'sk-test-not-real'
  const hooks = path.join(sample.repo, '.git', 'hooks')
  fs.mkdirSync(hooks, { recursive: true })
  fs.writeFileSync(path.join(hooks, 'pre-commit'), HOOK)
  fs.chmodSync(path.join(hooks, 'pre-commit'), 0o755)
})
afterEach(() => {
  for (const key of Object.keys(process.env)) if (!(key in saved)) delete process.env[key]
  Object.assign(process.env, saved)
  sample.cleanup()
})

async function estimate() {
  const { onboarding, folders } = readOnboardingConfig(sample.repo)
  const result = await buildEstimate({ plan: buildPlan({ root: sample.repo, folders, onboarding }), onboarding, fetchImpl: prices })
  fs.mkdirSync(workFolder(sample.repo), { recursive: true })
  writeJsonFile(path.join(workFolder(sample.repo), 'estimate.json'), result)
  return result
}

const run = async (extra = {}) => {
  const estimated = await estimate()
  return runOnboarding({ repo: sample.repo, approve: estimated.id, codex: path.join(STUBS, 'codex'), fetchImpl: checker, log: () => {}, commitTrailers: ['Co-Authored-By: Test <t@example.com>'], bodyFooter: 'Generated by the test.', ...extra })
}

const ghEntries = () => fs.readFileSync(logs.gh, 'utf8').trim().split('\n').map((l) => JSON.parse(l))
/** The body of a pull request as the run first opened it, and as it left it after the last edit. */
const bodies = (number) => {
  const edits = ghEntries().filter((e) => e.action === 'edit' && e.number === number)
  assert.ok(edits.length > 0, `the run edited pull request ${number}, but the gh log has no edit for it`)
  return { created: ghEntries().find((e) => e.action === 'create' && e.number === number).body, final: edits.at(-1).body }
}
const HEADING = "## Lines the repo's commit hook rewrote"

test('a line the commit hook rewrites outside the comment is named in the pull request body, and the report counts it', async () => {
  process.env.HOOK_MODE = 'rewrite'
  const messages = []
  const { report } = await run({ log: (m) => messages.push(m) })

  // The hook ran for every commit and was not skipped, and its edit was kept: it is in the branch.
  assert.equal(fs.readFileSync(logs.hookRuns, 'utf8').trim().split('\n').length, 6, 'three tries before the model and three commits')
  assert.match(sample.git('show', `${BRANCHES[1]}:packages/ui/src/PrimaryButton.tsx`), /disabled=\{Boolean\(disabled\)\}/)

  for (const body of Object.values(bodies(2))) {
    assert.ok(body.includes(HEADING), body)
    assert.ok(body.includes('Klaus did not write'), body)
    assert.ok(body.includes('- `packages/ui/src/PrimaryButton.tsx`, line 18:\n  - before: `      disabled={disabled}`\n  - after: `      disabled={Boolean(disabled)}`'), body)
  }
  // The purpose comment is Klaus's own text, so it is not listed, and the first and third pull requests had no rewrite.
  assert.equal(bodies(2).final.split('\n').filter((l) => l.startsWith('  - before:')).length, 1)
  for (const number of [1, 3]) for (const body of Object.values(bodies(number))) assert.ok(!body.includes(HEADING), body)

  assert.deepEqual(report.hookRewrites, [
    { step: 1, count: 0, files: [] },
    { step: 2, count: 1, files: [{ rel: 'packages/ui/src/PrimaryButton.tsx', count: 1 }] },
    { step: 3, count: 0, files: [] },
  ])
  assert.ok(messages.some((m) => /commit hook rewrote 1 line in 1 file in the commit for pull request 2/.test(m)), messages.join('\n'))
  assert.match(messages.join('\n'), /Pull request 2 of 3: https:\/\/github.com\/acme\/sample\/pull\/2, the repo's commit hook rewrote 1 line/)
})

test('a commit hook that rewrites nothing adds no section and the report counts 0 for every pull request', async () => {
  process.env.HOOK_MODE = 'none'
  const { report } = await run()
  assert.equal(fs.readFileSync(logs.hookRuns, 'utf8').trim().split('\n').length, 6)
  for (const number of [1, 2, 3]) for (const body of Object.values(bodies(number))) assert.ok(!body.includes('commit hook rewrote') && !body.includes(HEADING), body)
  assert.deepEqual(report.hookRewrites, [1, 2, 3].map((step) => ({ step, count: 0, files: [] })))
})

test('a repo with no commit hook adds no section either', async () => {
  fs.rmSync(path.join(sample.repo, '.git', 'hooks', 'pre-commit'))
  const { report } = await run()
  for (const number of [1, 2, 3]) assert.ok(!bodies(number).final.includes(HEADING))
  assert.deepEqual(report.hookRewrites.map((r) => r.count), [0, 0, 0])
})

test('a hook that rewrites many lines is listed up to a limit, with the rest counted, and a backtick in a line keeps its text', async () => {
  process.env.HOOK_MODE = 'many'
  const { report } = await run()
  const files = ['apps/web/src/app/dashboard/_components/ActivityFeed.tsx', 'apps/web/src/marketing/Hero.tsx', 'packages/ui/src/LinkButton.tsx', 'packages/ui/src/PrimaryButton.tsx']
  const lineCount = (file) => sample.git('show', `${BRANCHES[1]}:${file}`).replace(/\n$/, '').split('\n').length
  const total = files.map(lineCount).reduce((a, b) => a + b, 0)
  assert.ok(total > 40, `the sample's components have ${total} lines`)

  const second = report.hookRewrites.find((r) => r.step === 2)
  assert.equal(second.count, total)
  assert.deepEqual(second.files.map((f) => f.rel).sort(), files)
  assert.deepEqual(Object.fromEntries(second.files.map((f) => [f.rel, f.count])), Object.fromEntries(files.map((f) => [f, lineCount(f)])))
  assert.deepEqual(report.hookRewrites.filter((r) => r.step !== 2).map((r) => r.count), [0, 0])

  const body = bodies(2).final
  assert.equal(body.split('\n').filter((l) => l.startsWith('  - before:')).length, 40)
  assert.ok(body.includes(`rewrote ${total} lines in 4 files`), body)
  assert.ok(body.includes(`\n${total - 40} more are not listed here.\n`), body)
  assert.ok(body.includes("  - after: `` import type { ReactNode } from 'react' // `x` ``"), body)
  assert.ok(body.includes('  - before: (an empty line)'), 'a blank line is named as one')
})

test('a line the hook removes is placed by the line it followed, since it is not in the committed file', async () => {
  process.env.HOOK_MODE = 'remove'
  const { report } = await run()
  const body = bodies(2).final
  assert.ok(body.includes('- `packages/ui/src/PrimaryButton.tsx`, removed after line 17:\n  - before: `      disabled={disabled}`\n  - after: (the line was removed)'), body)
  assert.deepEqual(report.hookRewrites.map((r) => r.count), [0, 1, 0])
})

test('a line longer than the limit is cut, and the notice that says so is outside the code span', async () => {
  process.env.HOOK_MODE = 'long'
  await run()
  const line = `      disabled={disabled} // ${LONG}`
  assert.ok(line.length > 200)
  assert.ok(bodies(2).final.includes(`  - after: \`${line.slice(0, 200)}\` (cut here, ${line.length - 200} more characters)\n`), bodies(2).final)
})
