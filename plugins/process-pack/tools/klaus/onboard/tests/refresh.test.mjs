const REFRESH = 'klaus/onboarding-1-list-refresh'
const TICKET = 'docs/klaus/tickets/01-merge-primarybutton-into-button.md'
const OLD_TICKET = 'docs/klaus/tickets/02-merge-oldbutton-into-button.md'
const prices = async () => ({ ok: true, json: async () => ({ data: [{ id: 'z-ai/glm-5.3-flash', pricing: { prompt: '0.0000000392', completion: '0.0000002' } }] }) })

/**
 * A pre-commit hook that logs what is staged. With HOOK_MODE=tickets it refuses a commit that stages a ticket.
 * With HOOK_MODE=append it adds a line to the duplicates list and stages it again, as a formatter or an autofix would.
 */
const HOOK = `#!/bin/sh
echo "$(git diff --cached --name-status | tr '\\t\\n' ' ;')" >> "$HOOK_FILES_LOG"
if [ "$HOOK_MODE" = "append" ] && git diff --cached --name-only | grep -q -x docs/klaus/duplicates.md; then printf 'Added by the hook.\\n' >> docs/klaus/duplicates.md; git add docs/klaus/duplicates.md; fi
if [ "$HOOK_MODE" = "tickets" ] && git diff --cached --name-only | grep -q '/tickets/'; then echo "a ticket is refused here"; exit 1; fi
exit 0
`

let sample
let saved
let logs
let checks
const checker = async (_url, init) => {
  checks += 1
  const prompt = JSON.parse(init.body).messages[0].content
  const verdict = prompt.includes('Component: LinkButton') ? { verdict: 'fail', reason: 'it is also used for buttons that submit' } : { verdict: 'pass', reason: 'matches the places it is used' }
  return { ok: true, status: 200, json: async () => ({ choices: [{ message: { content: JSON.stringify(verdict) } }], usage: { prompt_tokens: 300, completion_tokens: 55, cost: 0.00003 } }) }
}

beforeEach(() => {
  sample = makeGitSample()
  logs = { codex: path.join(sample.base, 'codex.log'), gh: path.join(sample.base, 'gh.log'), hookFiles: path.join(sample.base, 'hook-files.log') }
  saved = { ...process.env }
  checks = 0
  process.env.PATH = `${STUBS}${path.delimiter}${process.env.PATH}`
  process.env.STUB_LOG = logs.codex
  process.env.STUB_GH_LOG = logs.gh
  process.env.HOOK_FILES_LOG = logs.hookFiles
  process.env.OPENROUTER_API_KEY = 'sk-test-not-real'
})
afterEach(() => {
  for (const key of Object.keys(process.env)) if (!(key in saved)) delete process.env[key]
  Object.assign(process.env, saved)
  sample.cleanup()
})

async function estimate() {
  const { onboarding, folders } = readOnboardingConfig(sample.repo)
  const result = await buildEstimate({ plan: buildPlan({ root: sample.repo, folders, onboarding }), onboarding, fetchImpl: prices })
  fs.mkdirSync(workFolder(sample.repo), { recursive: true })
  writeJsonFile(path.join(workFolder(sample.repo), 'estimate.json'), result)
  return result
}

/** The estimate as the command line makes it, with what it found of earlier runs: its text, and what it kept. */
async function estimateCommand() {
  const printed = []
  const original = console.log
  console.log = (...a) => printed.push(a.join(' '))
  try {
    assert.equal(await main(['estimate', '--repo', sample.repo], { fetchImpl: prices }), 0)
  } finally {
    console.log = original
  }
  return { text: printed.join('\n'), estimated: readJsonFile(path.join(workFolder(sample.repo), 'estimate.json'), 'Estimate') }
}

/** `onboard.mjs run` as a person types it, with its output kept. */
async function runCommand(args) {
  const printed = []
  const original = { log: console.log, error: console.error }
  console.log = (...a) => printed.push(a.join(' '))
  console.error = (...a) => printed.push(a.join(' '))
  try {
    return { code: await main(['run', '--repo', sample.repo, ...args], { fetchImpl: checker }), text: printed.join('\n') }
  } finally {
    Object.assign(console, original)
  }
}

const run = (estimated, extra = {}) => runOnboarding({ repo: sample.repo, approve: estimated.id, codex: path.join(STUBS, 'codex'), fetchImpl: checker, log: () => {}, commitTrailers: ['Co-Authored-By: Test <t@example.com>'], bodyFooter: 'Generated by the test.', ...extra })
const lines = (file) => (fs.existsSync(file) ? fs.readFileSync(file, 'utf8').trim().split('\n').filter(Boolean) : [])
const codexCalls = () => lines(logs.codex).length
const ghCalls = () => lines(logs.gh).map((l) => JSON.parse(l))
const tip = (ref) => sample.git('rev-parse', ref).trim()
const exists = (rel) => fs.existsSync(path.join(sample.repo, rel))
const branches = () => sample.git('branch', '--list', 'klaus/*', '--format=%(refname:short)').trim().split('\n').filter(Boolean).sort()

function installHook() {
  const file = path.join(sample.repo, '.git', 'hooks', 'pre-commit')
  fs.mkdirSync(path.dirname(file), { recursive: true })
  fs.writeFileSync(file, HOOK)
  fs.chmodSync(file, 0o755)
}

/**
 * Merges the first pull request, then puts its files on main as an older Klaus wrote them: a prop
 * type that names a build file, another line in the duplicates list, a ticket for a pair the plan
 * no longer finds and none for the one it does. Someone's own note in the tickets folder is not
 * the run's. INVENTORY.md is left as the plan writes it.
 */
function mergeAsAnOlderKlausWroteIt() {
  sample.git('merge', '-q', '--no-ff', BRANCHES[0], '-m', 'Merge pull request #1')
  const json = path.join(sample.repo, 'inventory.json')
  const list = JSON.parse(fs.readFileSync(json, 'utf8'))
  const button = list.entries.findIndex((e) => e.name === 'Button')
  list.entries[button].props[0].type = 'import("react/dist/index").ReactNode'
  fs.writeFileSync(json, `${JSON.stringify(list, null, 2)}\n`)
  fs.appendFileSync(path.join(sample.repo, 'docs/klaus/duplicates.md'), '\nA line an older Klaus wrote.\n')
  fs.rmSync(path.join(sample.repo, TICKET))
  fs.writeFileSync(path.join(sample.repo, OLD_TICKET), '# Merge OldButton into Button\n')
  fs.writeFileSync(path.join(sample.repo, 'docs/klaus/tickets/README.md'), 'Our own note about these tickets.\n')
  sample.git('add', '-A')
  sample.git('commit', '-qm', 'The first pull request, as an older Klaus wrote it')
  sample.git('push', '-q', 'origin', 'main')
  process.env.STUB_GH_MERGED = '1'
  return { button }
}

test('a merged first pull request that the plan no longer writes is refused without --refresh, and with it becomes a refresh from main with the second and third stacked on it', async () => {
  installHook()
  await run(await estimate())
  assert.deepEqual([codexCalls(), checks], [3, 4])
  const { button } = mergeAsAnOlderKlausWroteIt()

  // The estimate lists what a refresh would change, says the approval covers it, and prints the command with --refresh.
  const { text, estimated } = await estimateCommand()
  assert.match(text, /The run would refuse to start\. The first pull request's files are on main, but not as this plan writes them/)
  assert.ok(text.includes(`With --refresh the run does not refuse. It makes the first pull request again as a refresh: a pull request from the branch ${REFRESH}, cut from main and titled "Klaus onboarding 1 of 3 (refresh): the list of components at 1.0.0, and the duplicates", that holds only the files below as this plan writes them now. The second and third are stacked on it.`), text)
  assert.match(text, /A refresh would change 4 files:/)
  assert.ok(text.includes(`- inventory.json: changed, at entries[${button}].props[0].type (Button in packages/ui/src/Button.tsx) the plan writes "ReactNode", and it holds "import(\\"react/dist/index\\").ReactNode"`), text)
  assert.match(text, /- docs\/klaus\/duplicates\.md: changed, it has more text at the end/)
  assert.ok(text.includes(`- ${TICKET}: added`), text)
  assert.ok(text.includes(`- ${OLD_TICKET}: removed, no pair needs it now`), text)
  assert.doesNotMatch(text, /- INVENTORY\.md|tickets\/README\.md/)
  assert.match(text, /The decisions list and its pictures are drawn again when the run makes the refresh, and are in it where they differ from main\. A picture on main that the run does not draw again is removed\./)
  assert.match(text, new RegExp(`Approving the plan with --approve ${estimated.id} approves this refresh too\\.`))
  assert.ok(text.endsWith(`To run it with the refresh: onboard.mjs run --repo ${sample.repo} --approve ${estimated.id} --refresh`), text)

  // Without the flag the run refuses as before, and says how to go on.
  const before = ghCalls().length
  await assert.rejects(() => run(estimated), (e) => {
    assert.ok(e instanceof UserError)
    assert.match(e.message, /The first pull request's files are on main, but not as this plan writes them, so the run cannot continue from them and does not overwrite them\./)
    assert.match(e.message, /To bring them up to date through a pull request instead, run again with --refresh\. onboard\.mjs estimate lists the files it would change\./)
    return true
  })
  assert.deepEqual(ghCalls().slice(before).filter((c) => c.action !== 'list'), [], 'no pull request closed or made')
  assert.equal(sample.git('status', '--porcelain', '--untracked-files=all').trim(), '')

  // With it, from the command line, the first pull request is made again as a refresh. The model results are used again.
  fs.writeFileSync(logs.hookFiles, '')
  const { code, text: output } = await runCommand(['--approve', estimated.id, '--refresh'])
  assert.equal(code, 0, output)
  assert.deepEqual([codexCalls(), checks], [3, 4], 'no model call')
  const report = readJsonFile(path.join(workFolder(sample.repo), 'report.json'), 'Report')
  assert.equal(report.continuedAt, 1)
  assert.deepEqual(report.alreadyMerged, [])
  const changes = [
    { rel: 'docs/klaus/duplicates.md', change: 'changed' },
    { rel: TICKET, change: 'added' },
    { rel: OLD_TICKET, change: 'removed' },
    { rel: 'inventory.json', change: 'changed' },
  ]
  assert.deepEqual(report.refreshed, [{ step: 1, of: { number: 1, url: 'https://github.com/acme/sample/pull/1' }, changes }])

  const calls = ghCalls()
  assert.deepEqual(calls.filter((c) => c.action === 'close').map((c) => c.number), [2, 3])
  const created = calls.filter((c) => c.action === 'create')
  assert.deepEqual(created.slice(3).map((c) => [c.number, c.base, c.head]), [[4, 'main', REFRESH], [5, REFRESH, BRANCHES[1]], [6, BRANCHES[1], BRANCHES[2]]])
  assert.equal(created[3].title, 'Klaus onboarding 1 of 3 (refresh): the list of components at 1.0.0, and the duplicates')
  const body = calls.filter((c) => c.action === 'edit' && c.number === 4).at(-1).body
  assert.match(body, /This pull request refreshes #1, which is merged\./)
  assert.ok(body.includes(`- \`${OLD_TICKET}\`: removed, no pair needs it now.`), body)
  assert.ok(body.includes(`- \`${TICKET}\`: added.`), body)
  assert.match(body, /1\. #4: the list of components at 1\.0\.0, and the duplicates\. A refresh of #1, which is merged\./)
  assert.match(calls.filter((c) => c.action === 'edit' && c.number === 6).at(-1).body, /The run refreshed the first pull request/)

  // Cut from main, holding only the files that change; the second is cut from it and the third from the second.
  assert.equal(tip(`${REFRESH}^`), tip('main'))
  assert.equal(tip(`${BRANCHES[1]}^`), tip(REFRESH))
  assert.equal(tip(`${BRANCHES[2]}^`), tip(BRANCHES[1]))
  assert.deepEqual(sample.git('diff', '--name-status', 'main', REFRESH).trim().split('\n').sort(), [`A\t${TICKET}`, `D\t${OLD_TICKET}`, 'M\tdocs/klaus/duplicates.md', 'M\tinventory.json'])
  assert.equal(sample.git('show', `${REFRESH}:docs/klaus/tickets/README.md`), 'Our own note about these tickets.\n')
  assert.match(sample.git('log', '-1', '--format=%B', REFRESH), /^Refresh the component inventory at 1\.0\.0 and the duplicates list\n/)
  // The commit hook was tried on the refresh's files before anything else, and ran on the same files at the commit.
  const staged = lines(logs.hookFiles).map((l) => l.split(';').filter(Boolean).sort())
  const refreshFiles = [`A ${TICKET}`, `D ${OLD_TICKET}`, 'M docs/klaus/duplicates.md', 'M inventory.json']
  assert.deepEqual(staged[0], refreshFiles)
  assert.deepEqual(staged[3], refreshFiles)
  assert.equal(sample.git('rev-parse', '--abbrev-ref', 'HEAD').trim(), 'main')
  assert.equal(sample.git('status', '--porcelain', '--untracked-files=all').trim(), '')

  // Once the refresh merges, the first pull request is the plan's, and a run with --refresh continues at the second as any run does.
  sample.git('merge', '-q', '--no-ff', REFRESH, '-m', 'Merge pull request #4')
  sample.git('push', '-q', 'origin', 'main')
  process.env.STUB_GH_MERGED = '1,4'
  const after = await estimateCommand()
  assert.match(after.text, /as this plan writes them \(formatting aside\), so the run continues at the second/)
  assert.doesNotMatch(after.text, /--refresh/)
  const { report: again } = await run(after.estimated, { refresh: true })
  assert.equal(again.continuedAt, 2)
  assert.deepEqual(again.refreshed, [])
  assert.deepEqual(again.alreadyMerged, [{ step: 1, number: 4, url: 'https://github.com/acme/sample/pull/4' }])
})

test('a commit hook that refuses the refresh stops the run before any branch is made, and the merged files are as they were', async () => {
  installHook()
  await run(await estimate())
  mergeAsAnOlderKlausWroteIt()
  const { estimated } = await estimateCommand()
  const mainBefore = tip('main')
  const before = ghCalls().length
  process.env.HOOK_MODE = 'tickets'
  await assert.rejects(() => run(estimated, { refresh: true }), (e) => e instanceof UserError && /tried on the files of pull request 1 \(the refresh of the list and the duplicates\)/.test(e.message) && /a ticket is refused here/.test(e.message))
  assert.deepEqual(ghCalls().slice(before).filter((c) => c.action !== 'list'), [], 'no pull request closed or made')
  assert.equal(branches().includes(REFRESH), false)
  assert.equal(tip('main'), mainBefore)
  assert.equal(sample.git('status', '--porcelain', '--untracked-files=all').trim(), '')
  assert.equal(exists(OLD_TICKET), true, 'the ticket the check removed is back')
  assert.equal(exists(TICKET), false)
})

test('--refresh is held to the estimate: one that lists no refresh, or other files than main now needs, does not approve it', async () => {
  await run(await estimate())
  mergeAsAnOlderKlausWroteIt()
  // An estimate made the way a test makes it says nothing about earlier runs, so it lists no refresh.
  const bare = await estimate()
  await assert.rejects(() => run(bare, { refresh: true }), (e) => e instanceof UserError && new RegExp(`The estimate lists no refresh of the first pull request, so --approve ${bare.id} does not approve one\\. Run onboard\\.mjs estimate again and read it\\.`).test(e.message))

  const { estimated } = await estimateCommand()
  fs.writeFileSync(path.join(sample.repo, 'docs/klaus/tickets/03-remove-oldcard-from-web.md'), '# Remove OldCard\n')
  sample.git('add', '-A')
  sample.git('commit', '-qm', 'another old ticket')
  sample.git('push', '-q', 'origin', 'main')
  const before = ghCalls().length
  await assert.rejects(() => run(estimated, { refresh: true }), (e) => e instanceof UserError && /The files a refresh would change are not the ones the estimate lists\. Now: .*03-remove-oldcard-from-web\.md removed/.test(e.message))
  assert.deepEqual(ghCalls().slice(before).filter((c) => c.action !== 'list'), [])
  assert.equal(branches().includes(REFRESH), false)
})

test('a line the commit hook adds to a file of the refresh is named in the refresh pull request, and counted in the report', async () => {
  installHook()
  await run(await estimate())
  mergeAsAnOlderKlausWroteIt()
  const { estimated } = await estimateCommand()
  process.env.HOOK_MODE = 'append'
  const { code, text } = await runCommand(['--approve', estimated.id, '--refresh'])
  assert.equal(code, 0, text)
  const report = readJsonFile(path.join(workFolder(sample.repo), 'report.json'), 'Report')
  assert.deepEqual(report.hookRewrites.map((r) => [r.step, r.count]), [[1, 1], [2, 0], [3, 0]])
  assert.deepEqual(report.hookRewrites[0].files, [{ rel: 'docs/klaus/duplicates.md', count: 1 }])
  const body = ghCalls().filter((c) => c.action === 'edit' && c.number === 4).at(-1).body
  assert.match(body, /## Lines the repo's commit hook rewrote\n\nThe repo's pre-commit hook rewrote 1 line in 1 file/)
  assert.match(body, /- `docs\/klaus\/duplicates\.md`, line \d+:\n {2}- before: \(no line\)\n {2}- after: `Added by the hook\.`/)
  assert.match(sample.git('show', `${REFRESH}:docs/klaus/duplicates.md`), /Added by the hook\./, 'the hook\'s line is in the branch')
})
