const prices = async () => ({ ok: true, json: async () => ({ data: [{ id: 'z-ai/glm-5.3-flash', pricing: { prompt: '0.0000000392', completion: '0.0000002' } }] }) })

/** The checker's stand-in: passes everything except LinkButton. */
const checker = async (_url, init) => {
  const prompt = JSON.parse(init.body).messages[0].content
  const verdict = prompt.includes('Component: LinkButton') ? { verdict: 'fail', reason: 'it is also used for buttons that submit' } : { verdict: 'pass', reason: 'matches the places it is used' }
  return { ok: true, status: 200, json: async () => ({ choices: [{ message: { content: JSON.stringify(verdict) } }], usage: { prompt_tokens: 300, completion_tokens: 55, cost: 0.00003 } }) }
}

let sample
let saved
let logs
beforeEach(() => {
  sample = makeGitSample()
  logs = { codex: path.join(sample.base, 'codex.log'), gh: path.join(sample.base, 'gh.log') }
  saved = { ...process.env }
  process.env.PATH = `${STUBS}${path.delimiter}${process.env.PATH}`
  process.env.STUB_LOG = logs.codex
  process.env.STUB_GH_LOG = logs.gh
  process.env.OPENROUTER_API_KEY = 'sk-test-not-real'
})
afterEach(() => {
  for (const key of Object.keys(process.env)) if (!(key in saved)) delete process.env[key]
  Object.assign(process.env, saved)
  sample.cleanup()
})

async function estimate(repo = sample.repo) {
  const { onboarding, folders } = readOnboardingConfig(repo)
  const result = await buildEstimate({ plan: buildPlan({ root: repo, folders, onboarding }), onboarding, fetchImpl: prices })
  fs.mkdirSync(workFolder(repo), { recursive: true })
  writeJsonFile(path.join(workFolder(repo), 'estimate.json'), result)
  return result
}

const run = (estimated, extra = {}) => runOnboarding({ repo: sample.repo, approve: estimated.id, codex: path.join(STUBS, 'codex'), fetchImpl: checker, log: () => {}, commitTrailers: ['Co-Authored-By: Test <t@example.com>'], bodyFooter: 'Generated by the test.', ...extra })
const ghCalls = () => fs.readFileSync(logs.gh, 'utf8').trim().split('\n').map((l) => JSON.parse(l))
const codexCalls = () => fs.readFileSync(logs.codex, 'utf8').trim().split('\n').map((l) => JSON.parse(l))
const show = (branch, file) => sample.git('show', `${branch}:${file}`)
const files = (branch, base) => sample.git('diff', '--name-only', `${base}..${branch}`).trim().split('\n').filter(Boolean).sort()

test('the run makes three stacked branches and pull requests, with the files each should hold and no others', async () => {
  const estimated = await estimate()
  const { report } = await run(estimated)
  const [one, two, three] = BRANCHES

  assert.deepEqual(files(one, 'main'), [
    'INVENTORY.md',
    'docs/klaus/decisions.md',
    'docs/klaus/duplicates.json',
    'docs/klaus/duplicates.md',
    'docs/klaus/tickets/01-merge-primarybutton-into-button.md',
    'inventory.json',
  ])
  assert.deepEqual(files(two, one), [
    'INVENTORY.md',
    'apps/web/src/app/dashboard/_components/ActivityFeed.tsx',
    'apps/web/src/marketing/Hero.tsx',
    'docs/klaus/purposes.md',
    'inventory.json',
    'packages/ui/src/PrimaryButton.tsx',
  ])
  assert.deepEqual(files(three, two), [
    'apps/web/src/marketing/Hero.stories.tsx',
    'docs/klaus/stories.json',
    'docs/klaus/stories.md',
    'packages/ui/src/LinkButton.stories.tsx',
    'packages/ui/src/PrimaryButton.stories.tsx',
  ])

  // Each branch is cut from the one before.
  assert.equal(sample.git('merge-base', one, two).trim(), sample.git('rev-parse', one).trim())
  assert.equal(sample.git('merge-base', two, three).trim(), sample.git('rev-parse', two).trim())
  // The tree is back on main and clean.
  assert.equal(sample.git('rev-parse', '--abbrev-ref', 'HEAD').trim(), 'main')
  assert.equal(sample.git('status', '--porcelain').trim(), '')
  // Commits carry the trailer the caller gave.
  assert.match(sample.git('log', '-1', '--format=%B', two), /Co-Authored-By: Test <t@example\.com>/)

  const inventory1 = JSON.parse(show(one, 'inventory.json'))
  assert.equal(inventory1.entries.length, 5)
  assert.ok(inventory1.entries.every((e) => e.version === '1.0.0'))
  assert.equal(inventory1.entries.find((e) => e.name === 'Hero').purpose, null)

  const inventory2 = JSON.parse(show(two, 'inventory.json'))
  assert.match(inventory2.entries.find((e) => e.name === 'Hero').purpose.useWhen, /the Hero component/)
  assert.equal(inventory2.entries.find((e) => e.name === 'LinkButton').purpose, null, 'a purpose that failed its check is not written')
  assert.ok(inventory2.entries.every((e) => e.version === '1.0.0'))

  const story = show(three, 'apps/web/src/marketing/Hero.stories.tsx')
  assert.match(story, /component: Hero,\n  args: \{ title: 'Sample' \},/)
  assert.match(show(three, 'docs/klaus/stories.md'), /ActivityFeed.*calls useActivity from @\/hooks\/useActivity.*\/dashboard/)

  assert.deepEqual(report.pullRequests.map((p) => [p.step, p.number]), [[1, 1], [2, 2], [3, 3]])
})

test('the pull requests are based on the branch before, titled in order, and finished with the numbers once all exist', async () => {
  const estimated = await estimate()
  await run(estimated)
  const calls = ghCalls()
  const created = calls.filter((c) => c.action === 'create')
  assert.deepEqual(created.map((c) => [c.base, c.head]), [['main', BRANCHES[0]], [BRANCHES[0], BRANCHES[1]], [BRANCHES[1], BRANCHES[2]]])
  assert.match(created[0].title, /^Klaus onboarding 1 of 3/)
  const edits = calls.filter((c) => c.action === 'edit')
  assert.deepEqual(edits.map((c) => c.number), [1, 2, 3])
  for (const edit of edits) {
    assert.match(edit.body, /1\. #1: the list/)
    assert.match(edit.body, /3\. #3: stories/)
    assert.match(edit.body.trim(), /Generated by the test\.$/)
    assert.equal(edit.body.includes('\u2014'), false)
  }
  const last = edits[2].body
  assert.match(last, /\| Writer calls \| 3 \| 3 \| exact \| yes \|/)
  assert.match(last, /\| Checker calls \| 4 \| 4 \| exact \| yes \|/)
  assert.match(last, /\| Merge tickets \| 1 \| 1 \| exact \| yes \|/)
  const second = edits[1].body
  assert.match(second, /1 failed the check and are not in this pull request/)
  assert.match(second, /Writer: the local Codex CLI, gpt-5\.6-terra/)
})

test('the writer never sees the checker key, and runs in the folder it was given', async () => {
  await run(await estimate())
  const calls = codexCalls()
  assert.equal(calls.length, 3)
  assert.ok(calls.every((c) => c.key === null))
  const roots = calls.map((c) => c.args[c.args.indexOf('-C') + 1].replace(fs.realpathSync(sample.repo), ''))
  assert.deepEqual(roots, ['/apps/web/src/app/dashboard/_components', '/apps/web/src/marketing', '/packages/ui/src'])
})

test('the report holds the numbers the pull request shows, and the work folder holds the events', async () => {
  const { report } = await run(await estimate())
  assert.deepEqual([report.actual.writerCalls, report.actual.checkerCalls, report.actual.stories], [3, 4, 3])
  assert.ok(report.comparison.every((r) => r.within), JSON.stringify(report.comparison.filter((r) => !r.within)))
  assert.equal(report.purposes.find((p) => p.id.endsWith('#LinkButton')).status, 'dropped')
  const dir = workFolder(sample.repo)
  assert.ok(fs.existsSync(path.join(dir, 'report.json')))
  assert.equal(fs.readdirSync(path.join(dir, 'events')).length, 3)
  assert.equal(sample.git('status', '--porcelain').trim(), '', 'the run keeps its files inside the git folder')
})

