const prices = async () => ({ ok: true, json: async () => ({ data: [{ id: 'z-ai/glm-5.3-flash', pricing: { prompt: '0.0000000392', completion: '0.0000002' } }] }) })

let sample
let saved
let logs
let checks
/** The checker's stand-in: passes everything except LinkButton, and counts its calls. */
const checker = async (_url, init) => {
  checks += 1
  const prompt = JSON.parse(init.body).messages[0].content
  const verdict = prompt.includes('Component: LinkButton') ? { verdict: 'fail', reason: 'it is also used for buttons that submit' } : { verdict: 'pass', reason: 'matches the places it is used' }
  return { ok: true, status: 200, json: async () => ({ choices: [{ message: { content: JSON.stringify(verdict) } }], usage: { prompt_tokens: 300, completion_tokens: 55, cost: 0.00003 } }) }
}

/**
 * A pre-commit hook in the shape of Meridian's: it reads what is staged. HOOK_MODE picks what it refuses:
 * `all`, `components` (a staged component file with no story, as Meridian's story check does), or
 * `written` (the stub writer's sentence, which only a real purpose has). `format` refuses nothing
 * and rewrites and stages each staged file, as a formatter run by lint-staged does. Every run is logged.
 */
const HOOK = `#!/bin/sh
echo hook >> "$STUB_ORDER_LOG"
echo "$(git diff --cached --name-only | tr '\\n' ' ')" >> "$HOOK_FILES_LOG"
case "$HOOK_MODE" in
  all) echo "inventory.json:11743 no-home-path absolute home path"; exit 1 ;;
  components) if git diff --cached --name-only | grep -E '\\.tsx$' | grep -v -q '\\.stories\\.tsx$'; then echo "UI components must have a matching Storybook story"; exit 1; fi ;;
  written) if git diff --cached | grep -q 'is the right choice here'; then echo "a purpose comment was refused"; exit 1; fi ;;
  format) for f in $(git diff --cached --name-only); do printf '\n' >> "$f"; git add "$f"; done; mkdir -p tmp-hook-cache; echo x > tmp-hook-cache/seen ;;
esac
exit 0
`

function installHook(dir = path.join(sample.repo, '.git', 'hooks')) {
  fs.mkdirSync(dir, { recursive: true })
  fs.writeFileSync(path.join(dir, 'pre-commit'), HOOK)
  fs.chmodSync(path.join(dir, 'pre-commit'), 0o755)
}

beforeEach(() => {
  sample = makeGitSample()
  logs = { codex: path.join(sample.base, 'codex.log'), gh: path.join(sample.base, 'gh.log'), order: path.join(sample.base, 'order.log'), hookFiles: path.join(sample.base, 'hook-files.log') }
  saved = { ...process.env }
  checks = 0
  process.env.PATH = `${STUBS}${path.delimiter}${process.env.PATH}`
  process.env.STUB_LOG = logs.codex
  process.env.STUB_GH_LOG = logs.gh
  process.env.STUB_ORDER_LOG = logs.order
  process.env.HOOK_FILES_LOG = logs.hookFiles
  process.env.OPENROUTER_API_KEY = 'sk-test-not-real'
})
afterEach(() => {
  for (const key of Object.keys(process.env)) if (!(key in saved)) delete process.env[key]
  Object.assign(process.env, saved)
  sample.cleanup()
})

async function estimate() {
  const { onboarding, folders } = readOnboardingConfig(sample.repo)
  const result = await buildEstimate({ plan: buildPlan({ root: sample.repo, folders, onboarding }), onboarding, fetchImpl: prices })
  fs.mkdirSync(workFolder(sample.repo), { recursive: true })
  writeJsonFile(path.join(workFolder(sample.repo), 'estimate.json'), result)
  return result
}

const run = (estimated, extra = {}) => runOnboarding({ repo: sample.repo, approve: estimated.id, codex: path.join(STUBS, 'codex'), fetchImpl: checker, log: () => {}, commitTrailers: ['Co-Authored-By: Test <t@example.com>'], bodyFooter: 'Generated by the test.', ...extra })
const lines = (file) => (fs.existsSync(file) ? fs.readFileSync(file, 'utf8').trim().split('\n').filter(Boolean) : [])
const codexCalls = () => lines(logs.codex).length
const hookRuns = () => lines(logs.hookFiles).map((l) => l.trim().split(' ').filter(Boolean).sort())

/** The repo as the run must leave it after the hook check: on main, nothing changed, nothing staged, no branch made. */
function assertUntouched() {
  assert.equal(sample.git('rev-parse', '--abbrev-ref', 'HEAD').trim(), 'main')
  assert.equal(sample.git('status', '--porcelain', '--untracked-files=all').trim(), '')
  assert.equal(sample.git('diff', '--cached', '--name-only').trim(), '')
  assert.equal(sample.git('branch', '--list', 'klaus/*').trim(), '')
  assert.equal(fs.existsSync(path.join(sample.repo, 'docs')), false, 'the folders the check made are gone')
}

test('a commit hook that refuses stops the run before any model call, with the hook\'s message, and leaves the repo as it was', async () => {
  installHook()
  process.env.HOOK_MODE = 'all'
  const estimated = await estimate()
  await assert.rejects(() => run(estimated), (e) => e instanceof UserError && /refused them/.test(e.message) && /pull request 1/.test(e.message) && /no-home-path absolute home path/.test(e.message))
  assert.equal(codexCalls(), 0, 'the writer was not called')
  assert.equal(checks, 0, 'the checker was not called')
  assert.equal(fs.existsSync(logs.gh), false, 'no pull request was made')
  assert.match(fs.readFileSync(path.join(workFolder(sample.repo), 'hook-check.txt'), 'utf8'), /no-home-path/, 'the hook\'s whole output is kept')
  // The hook judged the first pull request's files, staged.
  assert.deepEqual(hookRuns(), [['INVENTORY.md', 'docs/klaus/decisions.md', 'docs/klaus/duplicates.json', 'docs/klaus/duplicates.md', 'docs/klaus/tickets/01-merge-primarybutton-into-button.md', 'inventory.json']])
  assertUntouched()
})

test('a hook that would refuse the purpose comments stops the run before the writer, though no purpose exists yet', async () => {
  installHook()
  process.env.HOOK_MODE = 'components'
  const estimated = await estimate()
  await assert.rejects(() => run(estimated), (e) => e instanceof UserError && /pull request 2 \(the purpose comments/.test(e.message) && /matching Storybook story/.test(e.message))
  assert.equal(codexCalls(), 0)
  assert.equal(checks, 0)
  const second = hookRuns()[1]
  assert.ok(second.includes('apps/web/src/marketing/Hero.tsx') && second.includes('docs/klaus/purposes.md') && second.includes('inventory.json'), second.join(' '))
  assertUntouched()
  // Every component file is back as it was: the placeholder comments are gone.
  assert.equal(fs.readFileSync(path.join(sample.repo, 'apps/web/src/marketing/Hero.tsx'), 'utf8').includes('placeholder'), false)
})

test('a hook that passes is tried on all three commits before the first model call, and the run goes on', async () => {
  installHook()
  const { report } = await run(await estimate())
  const order = lines(logs.order)
  assert.deepEqual(order.slice(0, 4), ['hook', 'hook', 'hook', 'codex'], order.join(' '))
  // Three tries before the model, then the three real commits.
  assert.equal(order.filter((l) => l === 'hook').length, 6)
  const [list, purposes, stories] = hookRuns()
  assert.ok(list.includes('inventory.json') && !list.some((f) => f.endsWith('.tsx')))
  assert.deepEqual(purposes.filter((f) => f.endsWith('.tsx')), ['apps/web/src/app/dashboard/_components/ActivityFeed.tsx', 'apps/web/src/marketing/Hero.tsx', 'packages/ui/src/LinkButton.tsx', 'packages/ui/src/PrimaryButton.tsx'])
  assert.deepEqual(stories, ['apps/web/src/marketing/Hero.stories.tsx', 'docs/klaus/stories.json', 'docs/klaus/stories.md', 'packages/ui/src/LinkButton.stories.tsx', 'packages/ui/src/PrimaryButton.stories.tsx'])
  assert.equal(report.pullRequests.length, 3)
  // What the hook was shown for the third commit is what the third commit holds.
  assert.deepEqual(sample.git('diff', '--name-only', `${BRANCHES[1]}..${BRANCHES[2]}`).trim().split('\n').sort(), stories)
})

test('a hook that rewrites and stages files, as a formatter does, is undone before the writer starts', async () => {
  installHook()
  process.env.HOOK_MODE = 'format'
  const estimated = await estimate()
  // Stops at the first writer call, to look at the tree the writer would get.
  let tree = null
  const look = (message) => {
    if (message.startsWith('Writer call 1 of')) {
      tree = { status: sample.git('status', '--porcelain', '--untracked-files=all').trim(), staged: sample.git('diff', '--cached', '--name-only').trim() }
      throw new Error('looked')
    }
  }
  await assert.rejects(() => run(estimated, { log: look }), /looked/)
  assert.deepEqual(tree, { status: '', staged: '' })
  assert.equal(lines(logs.hookFiles).length, 3)
  assert.equal(fs.existsSync(path.join(sample.repo, 'tmp-hook-cache', 'seen')), false, 'the file the hook made is gone')
})

test('a file of the run that the repo ignores stops the run before any model call, since git could not commit it', async () => {
  fs.appendFileSync(path.join(sample.repo, '.gitignore'), 'docs/\n')
  sample.git('commit', '-qam', 'ignore docs')
  sample.git('push', '-q', 'origin', 'main')
  const estimated = await estimate()
  await assert.rejects(() => run(estimated), (e) => e instanceof UserError && /git could not stage the files of pull request 1/.test(e.message) && /git add -- inventory.json failed: docs/.test(e.message))
  assert.deepEqual([codexCalls(), checks], [0, 0])
  assertUntouched()
})

test('the hook is found through core.hooksPath, and run directly when git has no git hook run', async () => {
  // A hooks folder in the repo, the way husky sets one up.
  installHook(path.join(sample.repo, 'tools', 'hooks'))
  sample.git('add', '-A')
  sample.git('commit', '-qm', 'hooks')
  sample.git('push', '-q', 'origin', 'main')
  sample.git('config', 'core.hooksPath', 'tools/hooks')
  process.env.HOOK_MODE = 'all'
  const estimated = await estimate()
  await assert.rejects(() => run(estimated), (e) => /git hook run pre-commit/.test(e.message) && /no-home-path/.test(e.message))
  await assert.rejects(() => run(estimated, { hookRun: false }), (e) => /tools\/hooks\/pre-commit, run directly/.test(e.message) && /no-home-path/.test(e.message))
  assert.equal(codexCalls(), 0)
  assert.equal(lines(logs.hookFiles).length, 2)
})

test('a run that stops after the writer keeps the writer\'s results: the next run makes no writer call and finishes', async () => {
  const estimated = await estimate()
  // Stops the process where the checker would start, as a crash or a ctrl-c would.
  const stopAtChecker = (message) => {
    if (message.startsWith('Checker:')) throw new Error('stopped')
  }
  await assert.rejects(() => run(estimated, { log: stopAtChecker }), /stopped/)
  assert.equal(codexCalls(), 3)
  assert.equal(checks, 0)
  assert.equal(sample.git('status', '--porcelain').trim(), '')

  const messages = []
  const { report } = await run(estimated, { log: (m) => messages.push(m) })
  assert.equal(codexCalls(), 3, 'the second run made no writer call')
  assert.equal(checks, 4)
  assert.equal(report.pullRequests.length, 3)
  assert.ok(messages.filter((m) => /reused from an earlier run of this plan \(no model call, no tokens\)/.test(m)).length === 3, messages.join('\n'))
  assert.deepEqual([report.actual.writerCalls, report.actual.writerReused.length, report.actual.writerTokens], [0, 3, 0])
  const row = (metric) => report.comparison.find((r) => r.metric === metric)
  assert.deepEqual([row('Writer calls').estimated, row('Writer calls').actual, row('Writer calls').within], [3, 3, true])
  assert.deepEqual([row('Writer tokens').estimated, row('Writer tokens').actual, row('Writer tokens').within], [0, 0, true])
  assert.match(report.notes.join('\n'), /0 calls made, and 3 calls reused from an earlier run of this plan, at no cost this time/)
  // The purposes are the ones the first run's writer wrote.
  assert.match(JSON.parse(sample.git('show', `${BRANCHES[1]}:inventory.json`)).entries.find((e) => e.name === 'Hero').purpose.useWhen, /the Hero component/)
})

test('a commit hook that refuses after the model work, as on Meridian, loses nothing: once it is fixed the next run calls no model', async () => {
  installHook()
  // Only a real purpose has this sentence, so the check before the model passes and the second commit is refused.
  process.env.HOOK_MODE = 'written'
  const estimated = await estimate()
  const messages = []
  await assert.rejects(() => run(estimated, { log: (m) => messages.push(m) }), /a purpose comment was refused/)
  assert.deepEqual([codexCalls(), checks], [3, 4])
  assert.ok(messages.some((m) => m.startsWith(`Branches made so far: ${BRANCHES[0]}, ${BRANCHES[1]}. Pull requests opened: https://github.com/acme/sample/pull/1.`)), messages.join('\n'))
  assert.ok(messages.some((m) => /The model's results are kept in .*klaus-onboarding\/results\//.test(m)))
  // The tree is clean and back on the base branch, so the next run can start once the branches are gone.
  assert.equal(sample.git('rev-parse', '--abbrev-ref', 'HEAD').trim(), 'main')
  assert.equal(sample.git('status', '--porcelain', '--untracked-files=all').trim(), '')
  // What the person does next: remove the branches the run made, fix what the hook refused, and run again.
  sample.git('branch', '-q', '-D', BRANCHES[0], BRANCHES[1])
  sample.git('push', '-q', 'origin', '--delete', BRANCHES[0])
  delete process.env.HOOK_MODE

  const { report } = await run(estimated)
  assert.deepEqual([codexCalls(), checks], [3, 4], 'no writer call and no checker call the second time')
  assert.equal(report.pullRequests.length, 3)
  assert.deepEqual([report.actual.checkerCalls, report.actual.checkerReused.length, report.actual.checkerTokens, report.actual.checkerUsd], [0, 4, 0, 0])
  assert.ok(report.comparison.every((r) => r.within !== false), JSON.stringify(report.comparison.filter((r) => r.within === false)))
  assert.equal(report.purposes.find((p) => p.name === 'LinkButton').status, 'dropped', 'a saved fail is still a fail')
  assert.match(report.notes.join('\n'), /0 checks made, 4 checks reused from an earlier run of this plan/)
})

test('a component whose text is rejected before the check is accounted for, so the checker calls still match the estimate', async () => {
  process.env.STUB_MODE = 'unsafe-text'
  const { report, state } = await run(await estimate())
  assert.equal(report.purposes.find((p) => p.name === 'Hero').status, 'rejected')
  assert.deepEqual([report.actual.checkerCalls, report.actual.checksNotReached], [3, ['apps/web/src/marketing/Hero.tsx#Hero']])
  const row = report.comparison.find((r) => r.metric === 'Checker calls')
  assert.deepEqual([row.estimated, row.actual, row.within], [4, 4, true])
  assert.match(report.notes.join('\n'), /of the 4 checks the estimate counted, 3 checks made, 1 component not checked, because the writer's text for it was rejected or not written/)
  // The token estimate it is held to is the one for the three checks made.
  const tokens = report.comparison.find((r) => r.metric === 'Checker tokens')
  const hero = state.estimate.purposes.checkerCallDetails.find((c) => c.id.endsWith('#Hero'))
  assert.equal(tokens.estimated, state.estimate.purposes.checkerTokens - hero.tokens)
})
